#!/usr/bin/env python3
"""Generate offsets_zero_linux.inc from offsets.h — every declared field
assigned {} so a Linux scan starts from zero, never from a Windows number."""
import re, sys
src = open('daemon/offsets.h').read().splitlines()
stack, out, pattern = [], [], re.compile(r'^\s*inline\s+\S+\s+(\w+)\s*=\s*[^;]+;')
ns_open = re.compile(r'^\s*namespace\s+(\w+)\s*\{')
ns_close = re.compile(r'^\s*\}\s*//?\s*namespace')
for line in src:
    m = ns_open.search(line)
    if m: stack.append(m.group(1)); continue
    if re.match(r'^\s*\}', line):
        if stack: stack.pop()
        continue
    m = pattern.match(line)
    if m and len(stack) >= 2 and stack[0] == 'Offsets':
        out.append('    Offsets::%s::%s = {};' % ('::'.join(stack[1:]), m.group(1)))
print('// GENERATED by tools/offsets_zero_gen.py from offsets.h — do not edit.')
print('// Linux-only: offsets_dynamic zeroes EVERY static number before a scan')
print('// fills in what it discovered, so no Windows value can survive on Sober.')
print('#ifdef __linux__')
print('inline void ZeroAll() {')
for l in out: print(l)
print('}')
print('#endif')
